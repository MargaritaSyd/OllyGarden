// Regenerates src/lib/instrumentation-score-rules.ts from the Instrumentation Score specification.
// Usage: node scripts/sync-instrumentation-score-rules.mjs [path-to-local-spec-checkout]
// Without a path it shallow-clones https://github.com/instrumentation-score/spec into a temp dir.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const repository = "https://github.com/instrumentation-score/spec";
const out = "src/lib/instrumentation-score-rules.ts";
const impacts = ["Critical", "Important", "Normal", "Low"];

const localSpec = process.argv[2];
const specDir = localSpec ?? mkdtempSync(join(tmpdir(), "instrumentation-score-spec-"));
if (!localSpec) {
  execFileSync("git", ["clone", "--quiet", "--depth", "1", repository, specDir], { stdio: "inherit" });
}

try {
  const git = (...args) => execFileSync("git", ["-C", specDir, ...args], { encoding: "utf8" }).trim();
  // The page links each rule to this commit, so the rules must be exactly what it contains.
  const dirty = git("status", "--porcelain", "--", "rules");
  if (dirty) throw new Error(`${specDir}/rules has uncommitted changes; commit or stash them first:\n${dirty}`);
  const commit = git("rev-parse", "HEAD");
  const date = git("log", "-1", "--format=%cs");

  // Tracked files only, so an ignored or untracked rule can't slip past the status check.
  const rules = git("ls-files", "--", "rules")
    .split("\n")
    .filter((path) => /^rules\/[A-Z]+-\d+\.md$/.test(path))
    .sort()
    .map((path) => parseRule(path.slice("rules/".length), readFileSync(join(specDir, path), "utf8")));

  writeFileSync(out, render({ commit, date, rules }));
  console.log(`✓ ${rules.length} rules from ${repository} at ${commit.slice(0, 7)} → ${out}`);
} finally {
  if (!localSpec) rmSync(specDir, { recursive: true, force: true });
}

function field(markdown, name) {
  // Rules write both "**Criteria:**" and "**Criteria**:".
  const match = markdown.match(new RegExp(`\\*\\*${name}:?\\*\\*:?[ \\t]*([^\\n]*)`));
  return match?.[1].replace(/\\(.)/g, "$1").trim();
}

function parseRule(file, markdown) {
  const id = field(markdown, "Rule ID");
  const description = field(markdown, "Description");
  const target = field(markdown, "Target");
  const impact = field(markdown, "Impact");
  const criteria = field(markdown, "Criteria") ?? "";

  if (`${id}.md` !== file) throw new Error(`${file}: rule ID ${id} does not match the file name`);
  if (!description || !target) throw new Error(`${file}: missing description or target`);
  if (!impacts.includes(impact)) throw new Error(`${file}: unknown impact ${impact}`);

  return {
    id,
    description: description.endsWith(".") ? description : `${description}.`,
    target,
    impact,
    criteriaDefined: criteria !== "" && !/^TODO\b/i.test(criteria),
  };
}

function render({ commit, date, rules }) {
  const body = rules
    .map((rule) => `  {\n${Object.entries(rule).map(([key, value]) => `    ${key}: ${JSON.stringify(value)},`).join("\n")}\n  },`)
    .join("\n");

  return `// Generated by scripts/sync-instrumentation-score-rules.mjs; do not edit by hand.
// Re-run the script to pick up rule changes from the specification.

export type ScoreImpact = "Critical" | "Important" | "Normal" | "Low";

export type SpecRule = {
  id: string;
  description: string;
  /** The OTLP element the rule checks, as the specification names it. */
  target: string;
  impact: ScoreImpact;
  /** False while the specification still marks the rule's criteria as TODO. */
  criteriaDefined: boolean;
};

export const specSource = {
  repository: ${JSON.stringify(repository)},
  commit: ${JSON.stringify(commit)},
  date: ${JSON.stringify(date)},
} as const;

export const specRules = [
${body}
] as const satisfies readonly SpecRule[];

export type SpecRuleId = (typeof specRules)[number]["id"];
`;
}
