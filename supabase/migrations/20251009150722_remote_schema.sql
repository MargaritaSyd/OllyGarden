CREATE OR REPLACE VIEW "public"."new_applicants" AS
 SELECT
        CASE
            WHEN ("substring"("job_applications"."full_name", '(.*) '::"text") IS NULL) THEN "job_applications"."full_name"
            ELSE "substring"("job_applications"."full_name", '(.*) '::"text")
        END AS "first_name",
        CASE
            WHEN ("substring"("job_applications"."full_name", ' (.*)'::"text") IS NULL) THEN '-'::"text"
            ELSE "substring"("job_applications"."full_name", ' (.*)'::"text")
        END AS "last_name",
    "job_applications"."email",
    ''::"text" AS "phone",
    "job_applications"."linkedin_url" AS "linkedin",
    "job_applications"."github_url" AS "website",
    "job_applications"."job_id" AS "note",
    "job_applications"."job_title" AS "tags"
   FROM "public"."job_applications"
  WHERE ("job_applications"."created_at" >= ("now"() - '00:30:00'::interval))
  ORDER BY "job_applications"."created_at" DESC;


ALTER TABLE "public"."new_applicants" OWNER TO "postgres";


CREATE OR REPLACE VIEW "public"."test_applicants" AS
 SELECT "substring"("job_applications"."full_name", '(.*) '::"text") AS "first_name",
    "substring"("job_applications"."full_name", ' (.*)'::"text") AS "last_name",
    "job_applications"."email",
    ''::"text" AS "phone",
    "job_applications"."linkedin_url" AS "linkedin",
    "job_applications"."github_url" AS "website",
    "job_applications"."job_id" AS "note",
    "job_applications"."job_title" AS "tags"
   FROM "public"."job_applications"
  WHERE ("job_applications"."created_at" >= ("now"() - '83:20:00'::interval))
  ORDER BY "job_applications"."created_at" DESC;


